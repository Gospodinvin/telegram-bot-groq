def parse_diploma_text(text: str) -> list:
    pattern = r'===\s*(.+?)\s*===\n(.*?)(?=(?:===\s*.+?\s*===|\Z))'
    matches = re.findall(pattern, text, re.DOTALL)
    return [(h.strip(), b.strip()) for h, b in matches if b.strip()]