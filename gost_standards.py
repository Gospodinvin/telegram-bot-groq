def detect_standard(topic: str, university_hint: str = None) -> str:
    t_lower = topic.lower()
    detected_uni = None
    if university_hint:
        h_lower = university_hint.lower()
        for uk, uv in UNIVERSITIES.items():
            if any(k in h_lower for k in uv['keywords']):
                detected_uni = uk
                break
    if not detected_uni:
        for uk, uv in UNIVERSITIES.items():
            if any(k in t_lower for k in uv['keywords']):
                detected_uni = uk
                break
    if detected_uni:
        uni = UNIVERSITIES[detected_uni]
        if 'exceptions' in uni:
            for std_key, kw_list in uni['exceptions'].items():
                if any(k in t_lower for k in kw_list):
                    return std_key
        return uni.get('default_standard', 'gost_7.32-2017')
    global_keywords = {
        'apa_7': ['психолог', 'социолог', 'бизнес', 'поведение', 'мотивация'],
        'mla_9': ['литератур', 'языкознание', 'культуролог', 'филолог'],
        'chicago_17': ['истори', 'искусств', 'археолог', 'музееведение'],
        'harvard': ['экономик', 'менеджмент', 'маркетинг', 'международные отношения', 'бизнес-план'],
        'ieee': ['инженер', 'робот', 'it', 'программир', 'радио', 'схема', 'электрон'],
        'vancouver': ['медицин', 'биолог', 'фармаколог', 'клинич'],
        'oscola': ['право', 'юриспруденция', 'закон', 'гк рф', 'ук рф', 'суд'],
        'gost_2.105-95': ['чертеж', 'схема', 'механик', 'деталь', 'сборочный', 'станок'],
    }
    for std_key, keywords in global_keywords.items():
        if any(k in t_lower for k in keywords):
            return std_key
    return 'gost_7.32-2017'


